/**
 * Extract the AWS service glyphs used by `src/backend/diagram/aws.ts` from
 * draw.io's published aws4 stencil set into `src/ui/aws-glyphs.ts`.
 *
 * The inline preview cannot reference draw.io's shape library the way the
 * generated .drawio file can, so the paths for our catalog — and only our
 * catalog — are converted to SVG and checked in.
 *
 *   node tools/build-aws-glyphs.mjs path/to/aws4.xml
 *
 * Source: https://github.com/jgraph/drawio  src/main/webapp/stencils/aws4.xml
 * These are AWS's official Architecture Icons as redistributed by draw.io.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const stencilPath = process.argv[2];
if (!stencilPath) {
  console.error('usage: node tools/build-aws-glyphs.mjs <aws4.xml>');
  process.exit(1);
}

const raw = readFileSync(stencilPath, 'utf8');
const catalog = readFileSync('src/backend/diagram/aws.ts', 'utf8');
const icons = [...new Set([...catalog.matchAll(/resIcon: '([a-z0-9_]+)'/g)].map((m) => m[1]))].sort();

const num = (value) => {
  const n = Number(value);
  // Trim to 2dp: these are 56px-tall glyphs, further precision is noise.
  return String(Math.round(n * 100) / 100);
};

/** mxGraph stencil path commands -> an SVG path `d` string. */
function toPathData(shapeXml) {
  const parts = [];
  const commands = shapeXml.matchAll(/<(move|line|curve|arc|close)\b([^>]*)\/?>/g);
  for (const [, kind, attrText] of commands) {
    const a = Object.fromEntries(
      [...attrText.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
    );
    if (kind === 'move') parts.push(`M${num(a.x)} ${num(a.y)}`);
    else if (kind === 'line') parts.push(`L${num(a.x)} ${num(a.y)}`);
    else if (kind === 'curve')
      parts.push(`C${num(a.x1)} ${num(a.y1)} ${num(a.x2)} ${num(a.y2)} ${num(a.x3)} ${num(a.y3)}`);
    else if (kind === 'arc')
      parts.push(
        `A${num(a.rx)} ${num(a.ry)} ${num(a['x-axis-rotation'])} ` +
          `${a['large-arc-flag']} ${a['sweep-flag']} ${num(a.x)} ${num(a.y)}`,
      );
    else parts.push('Z');
  }
  return parts.join('');
}

const entries = [];
const missing = [];
for (const icon of icons) {
  const name = icon.replace(/_/g, ' ');
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = raw.match(new RegExp(`<shape\\b[^>]*name="${escaped}"[^>]*>[\\s\\S]*?</shape>`));
  if (!match) {
    missing.push(icon);
    continue;
  }
  const shapeXml = match[0];
  const w = Number(/\bw="([\d.]+)"/.exec(shapeXml)?.[1] ?? 0);
  const h = Number(/\bh="([\d.]+)"/.exec(shapeXml)?.[1] ?? 0);
  const d = toPathData(shapeXml);
  if (!d || !w || !h) {
    missing.push(icon);
    continue;
  }
  entries.push({ icon, w, h, d });
}

if (missing.length > 0) {
  console.error(`could not extract: ${missing.join(', ')}`);
  process.exit(1);
}

const body = entries
  .map((e) => `  ${/^[a-z][a-z0-9_]*$/.test(e.icon) ? e.icon : `'${e.icon}'`}: ` +
    `{ w: ${e.w}, h: ${e.h}, d: '${e.d}' },`)
  .join('\n');

const out = `/**
 * AWS service glyphs for the inline preview.
 *
 * GENERATED by tools/build-aws-glyphs.mjs from draw.io's published aws4 stencil
 * set — do not edit by hand. Keyed by the same \`resIcon\` name the generated
 * .drawio file references, so the preview and the file show the same artwork.
 *
 * These are AWS's official Architecture Icons. AWS permits their use in
 * architecture diagrams; see AWS's Architecture Icons terms before shipping
 * this app outside your organisation.
 *
 * Each glyph is a single filled path in its own \`w\` x \`h\` coordinate space.
 */

export interface AwsGlyph {
  w: number;
  h: number;
  /** SVG path data, filled with the tile's foreground colour. */
  d: string;
}

export const AWS_GLYPHS: Record<string, AwsGlyph> = {
${body}
};
`;

writeFileSync('src/ui/aws-glyphs.ts', out);
console.log(`extracted ${entries.length} glyphs -> src/ui/aws-glyphs.ts (${(out.length / 1024).toFixed(1)} KB)`);
